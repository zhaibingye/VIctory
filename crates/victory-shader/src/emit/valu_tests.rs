    words.push(S_ENDPGM);
    let shader = lower_cs32(&words, &[(4, ResourceType::Uav, 0, 8)], true);

    let key = |lo: u32, hi: u32| u64::from(lo) | u64::from(hi) << 32;
    let a = |l: u32| key(31 - l, (l & 3) << 30);
